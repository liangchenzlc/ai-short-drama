async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const read = () => page.evaluate(async () => (await fetch('/api/v1/projects/10/episodes/20/assembly')).json());
  const save = async () => assert(await page.evaluate(() => window.assemblyBarrier.flush()), 'Save failed');
  const seek = async seconds => {
    await page.getByRole('spinbutton',{name:'定位时间（秒）'}).fill(String(seconds));
    await page.getByRole('spinbutton',{name:'定位时间（秒）'}).press('Tab');
    await page.waitForFunction(seconds => Math.abs(Number(document.querySelector('.assembly-jump input').value) - seconds) < .05, seconds);
  };
  await seek(1);
  await page.getByRole('button',{name:'分割',exact:true}).click();
  await save();
  let state = await read();
  assert(state.clips.length === 4, 'Split did not create two instances');
  assert(state.clips[0].trim_out_ms === 1000 && state.clips[1].trim_in_ms === 1000, 'Split boundaries differ');
  await page.getByRole('button',{name:'删除片段',exact:true}).click();
  await save();
  assert((await read()).clips.length === 3, 'Delete failed');
  await page.getByRole('button',{name:'撤销',exact:true}).click();
  await save();
  assert((await read()).clips.length === 4, 'Undo failed');
  await page.getByRole('button',{name:'重做',exact:true}).click();
  await save();
  assert((await read()).clips.length === 3, 'Redo failed');
  await page.getByRole('button',{name:'添加镜头 2',exact:true}).click();
  await save();
  state = await read();
  assert(state.clips.length === 4 && state.clips[3].shot_id === '12', 'Add from source failed');
  for (let i=0;i<15;i++) await page.locator('.assembly-track-clip[aria-pressed="true"]').press('Alt+Shift+ArrowRight');
  await save();
  assert((await read()).clips[3].trim_in_ms === 500, 'Trim did not persist');
  await page.getByRole('button',{name:'前移',exact:true}).click();
  await save();
  assert((await read()).clips[2].trim_in_ms === 500, 'Reorder lost edit');
  await page.reload();
  await page.getByRole('heading',{name:'成片合成与导出',exact:true}).waitFor();
  await page.waitForFunction(()=>document.querySelector('.assembly-screen video.is-active')?.readyState>=2);
  assert((await read()).clips.length === 4, 'Refresh lost split edit');
  await seek(.8);
  await page.getByRole('button',{name:'播放',exact:true}).click();
  await page.waitForFunction(()=>Number(document.querySelector('.assembly-jump input').value)>1.2);
  await page.getByRole('button',{name:'暂停',exact:true}).click();
  assert(!await page.getByRole('alert').count(), 'Playback raised error');
  await page.locator('.assembly-export-bar').getByRole('button',{name:'导出成片',exact:true}).click();
  await page.getByRole('button',{name:'开始合成',exact:true}).click();
  await page.locator('.assembly-mode-switch').getByRole('button',{name:'导出成片',exact:true}).click();
  await page.getByRole('region',{name:'实际成片播放'}).waitFor();
  assert(await page.getByRole('button',{name:'分割',exact:true}).isDisabled(), 'Rendered timeline allowed editing');
  await page.getByRole('button',{name:'剪辑预览',exact:true}).click();
  await page.getByRole('button',{name:'合成预览',exact:true}).click();
  await page.getByText('已合成预览',{exact:false}).waitFor();
  await page.getByRole('button',{name:'剪辑预览',exact:true}).click();
  await seek(.5);
  console.log(JSON.stringify({passed:true, clips:(await read()).clips.length}));
}
