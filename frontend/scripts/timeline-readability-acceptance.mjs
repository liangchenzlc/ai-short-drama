async (page) => {
  const assert=(value,message)=>{if(!value)throw new Error(message);};
  const read=()=>page.evaluate(async()=>(await fetch('/api/v1/projects/10/episodes/20/assembly')).json());
  const save=async()=>assert(await page.evaluate(()=>window.assemblyBarrier.flush()),'Save failed');
  await page.setViewportSize({width:1440,height:1080});
  await page.getByRole('button',{name:'专注剪辑',exact:true}).click();
  assert(!await page.locator('.assembly-inspector').count(),'Inspector still exists');
  assert(!await page.getByRole('button',{name:'重置布局',exact:true}).count(),'Reset still exists');
  await page.waitForFunction(()=>[...document.querySelectorAll('.assembly-sprite')].some(img=>img.complete&&img.naturalWidth===480));
  assert(await page.locator('.assembly-filmstrip-cell').count()>3,'Filmstrip is not a sequence');
  const indices=await page.locator('.assembly-track-clip').first().locator('.assembly-filmstrip-cell').evaluateAll(nodes=>nodes.map(n=>Number(n.dataset.frameIndex)));
  assert(new Set(indices).size>=2,'Clip repeats one source frame');
  const stateBefore=await read();
  // Visible playhead remains at the same screen position during zoom.
  await page.getByRole('spinbutton',{name:'定位时间（秒）'}).fill('1.5');
  await page.getByRole('spinbutton',{name:'定位时间（秒）'}).press('Tab');
  await page.waitForFunction(()=>Math.abs(Number(document.querySelector('.assembly-jump input').value)-1.5)<.04);
  const cursor=page.locator('.timeline-editor-cursor');
  const x=(await cursor.boundingBox()).x;
  await page.getByRole('button',{name:'放大时间轴',exact:true}).click();
  await page.waitForFunction(x=>Math.abs(document.querySelector('.timeline-editor-cursor').getBoundingClientRect().x-x)<2,x);
  await page.getByRole('button',{name:'适应全部',exact:true}).click();
  const first=page.locator('.assembly-track-clip').first();
  const start=(await read()).clips[0].trim_in_ms;
  await first.press('Alt+Shift+ArrowRight');
  await save();
  assert((await read()).clips[0].trim_in_ms===start+33,'Frame keyboard trim failed');
  assert((await page.locator('.assembly-timeline-feedback').textContent()).includes('裁剪完成'),'Missing trim completion feedback');
  await page.getByRole('button',{name:'撤销',exact:true}).click(); await save();
  assert((await read()).clips[0].trim_in_ms===start,'Trim undo failed');
  const left=page.locator('.timeline-editor-action-left-stretch').first();
  const box=await left.boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2); await page.mouse.down();
  await page.mouse.move(box.x+50,box.y+box.height/2,{steps:12});
  const live=await page.locator('.assembly-timeline-feedback').textContent();
  assert(live.includes('入点')&&live.includes('出点')&&live.includes('保留'),'Missing live trim times');
  await page.mouse.up(); await save();
  assert((await read()).clips[0].trim_in_ms>start,'Pointer trim did not persist');
  await page.getByRole('button',{name:'恢复完整',exact:true}).click(); await save();
  const moved=await first.boundingBox();
  await page.mouse.move(moved.x+moved.width*.7,moved.y+moved.height/2); await page.mouse.down();
  await page.mouse.move(moved.x+moved.width*2.5,moved.y+moved.height/2,{steps:12});
  assert(await page.locator('.assembly-insert-marker').isVisible(),'Missing reorder insertion line');
  assert((await page.locator('.assembly-timeline-feedback').textContent()).includes('松开'),'Missing reorder target feedback');
  await page.mouse.up(); await save();
  assert((await read()).clips[0].id!==stateBefore.clips[0].id,'Reorder did not commit');
  await page.getByRole('button',{name:'撤销',exact:true}).click(); await save();
  await page.getByRole('button',{name:'片段静音',exact:true}).click(); await save();
  assert((await read()).clips.some(c=>c.id===stateBefore.clips[0].id&&c.muted),'Toolbar mute failed');
  await page.getByRole('button',{name:'恢复原声',exact:true}).click(); await save();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'.impeccable/review/timeline-readability-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('separator',{name:'调整播放器高度'}).waitFor({state:'hidden'});
  await page.getByRole('button',{name:'适应全部',exact:true}).click();
  assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'Mobile overflow');
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'.impeccable/review/timeline-readability-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1080});
  await page.getByRole('button',{name:'退出专注剪辑',exact:true}).click();
  return {passed:true,sampledFrames:true,zoomAnchored:true,liveTrim:true,reorderTarget:true,keyboardTrim:true};
}
