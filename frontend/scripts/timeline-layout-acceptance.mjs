async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const player = page.getByRole('region',{name:'时间轴成片预览'});
  const state = () => page.evaluate(async ()=>(await fetch('/api/v1/projects/10/episodes/20/assembly')).json());
  const before = await state();
  const errors=[]; page.on('pageerror',error=>errors.push(String(error)));
  await page.setViewportSize({width:1440,height:1080});
  if (await page.getByRole('button',{name:'退出专注剪辑',exact:true}).count()) await page.getByRole('button',{name:'退出专注剪辑',exact:true}).click();
  await page.evaluate(()=>localStorage.removeItem('short-drama:assembly-layout:v1'));
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('video.is-active')?.readyState>=2);
  await page.evaluate(()=>{window.layoutVideo=document.querySelector('video.is-active');});
  const regularHeight = (await page.locator('.assembly-screen').boundingBox()).height;
  await player.getByRole('button',{name:'播放',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('video.is-active')?.currentTime>.2);
  await page.getByRole('button',{name:'专注剪辑',exact:true}).click();
  assert((await page.locator('.assembly-screen').boundingBox()).height>regularHeight,'Focus did not enlarge player');
  assert(await page.evaluate(()=>window.layoutVideo===document.querySelector('video.is-active')), 'Focus remounted active video');
  assert(await player.getByRole('button',{name:'暂停',exact:true}).isVisible(), 'Focus stopped playback');
  await player.getByRole('button',{name:'暂停',exact:true}).click();
  const time = await page.evaluate(()=>document.querySelector('video.is-active').currentTime);
  await page.getByRole('button',{name:'收起素材',exact:true}).click();
  assert(await page.getByRole('complementary',{name:'分镜视频素材'}).isHidden(), 'Media bin not hidden');
  assert(!await page.getByRole('button',{name:'重置布局',exact:true}).count(), 'Removed reset control still exists');
  assert(!await page.locator('.assembly-inspector').count(), 'Removed inspector still exists');
  assert(await page.evaluate(()=>window.layoutVideo===document.querySelector('video.is-active')), 'Panel toggle remounted player');
  assert(Math.abs(await page.evaluate(()=>document.querySelector('video.is-active').currentTime)-time)<.05,'Panel toggle lost playback time');
  const handle=page.getByRole('separator',{name:'调整播放器高度'});
  const height=Number(await handle.getAttribute('aria-valuenow'));
  const box=await handle.boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2); await page.mouse.down();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2-80,{steps:8}); await page.mouse.up();
  assert(Number(await handle.getAttribute('aria-valuenow'))===height-80,'Player resize did not match pointer');
  await handle.press('ArrowDown');
  const savedHeight=height-60;
  assert(Number(await handle.getAttribute('aria-valuenow'))===savedHeight,'Keyboard resize failed');
  const track=page.getByRole('separator',{name:'调整轨道高度'});
  await track.press('ArrowDown'); await track.press('ArrowDown');
  assert((await page.locator('.timeline-editor').boundingBox()).height===192,'Track did not resize');
  await page.waitForFunction(expected=>JSON.parse(localStorage.getItem('short-drama:assembly-layout:v1')).playerHeight===expected,savedHeight);
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('video.is-active')?.readyState>=2);
  assert(await page.getByRole('button',{name:'专注剪辑',exact:true}).isVisible(),'Focus should start off after reload');
  assert(await page.getByRole('button',{name:'展开素材',exact:true}).isVisible(),'Media preference lost');
  assert(Number(await page.getByRole('separator',{name:'调整播放器高度'}).getAttribute('aria-valuenow'))===savedHeight,'Height preference lost');
  assert((await page.locator('.timeline-editor').boundingBox()).height===192,'Track preference lost');
  const after=await state();
  assert(JSON.stringify(before)===JSON.stringify(after),'Layout changed editing data');
  await page.evaluate(()=>localStorage.removeItem('short-drama:assembly-layout:v1'));
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('video.is-active')?.readyState>=2);
  await page.getByRole('button',{name:'专注剪辑',exact:true}).click();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'.impeccable/review/timeline-focus-desktop.png',fullPage:true});
  await page.setViewportSize({width:900,height:900});
  assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'Intermediate overflow');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('separator',{name:'调整播放器高度'}).waitFor({state:'hidden'});
  assert(!await page.getByRole('separator',{name:'调整播放器高度'}).count(),'Desktop handle should not crowd mobile');
  assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'Mobile overflow');
  await page.screenshot({path:'.impeccable/review/timeline-focus-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'退出专注剪辑',exact:true}).click();
  await page.setViewportSize({width:1440,height:1080});
  await page.getByRole('button',{name:'专注剪辑',exact:true}).click();
  await page.getByRole('button',{name:'导出记录',exact:true}).click();
  await page.getByRole('dialog',{name:'导出记录'}).press('Escape');
  assert(await page.getByRole('button',{name:'退出专注剪辑',exact:true}).isVisible(),'Dialog Escape also exited focus mode');
  await page.getByRole('button',{name:'退出专注剪辑',exact:true}).press('Escape');
  assert(await page.getByRole('button',{name:'专注剪辑',exact:true}).isVisible(),'Escape failed to exit focus mode');
  assert(!errors.length, errors.join('\n'));
  return {passed:true,playbackPreserved:true,layoutPersisted:true,editingDataUnchanged:true,mobileOverflow:false};
}
