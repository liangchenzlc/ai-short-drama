import { expect, test } from '@playwright/test';

for (const width of [1440, 390]) test(`feedback preserves editors and recovery actions at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/e2e/creation/fixtures/feedback-fixture.html');
  const editor = page.getByRole('textbox', { name: '原始编辑器', exact: true });
  const original = await editor.boundingBox();
  await page.getByRole('button', { name: '后台准备', exact: true }).click();
  await expect(page.locator('.studio-message')).toHaveCount(0);
  expect(await editor.boundingBox()).toEqual(original);
  await page.getByRole('button', { name: '触发报错', exact: true }).click();
  await expect(page.locator('.studio-message .ant-message-error')).toBeVisible();
  await expect(page.locator('.studio-message')).toContainText('图片上传失败');
  expect(await editor.boundingBox()).toEqual(original);
  await page.getByRole('button', { name: '关闭提示', exact: true }).click();
  await expect(page.locator('.studio-message')).toHaveCount(0);
  const saveEntry = page.getByRole('button', { name: /保存状态：需处理/ });
  await saveEntry.click();
  await page.getByRole('button', { name: '重试原操作', exact: true }).focus();
  await page.keyboard.press('Escape');
  await expect(saveEntry).toBeFocused();
  await expect(saveEntry).toHaveAttribute('aria-expanded', 'false');
  await saveEntry.press('Enter');
  await page.getByRole('button', { name: '保存详情内确认', exact: true }).click();
  const saveConfirmation = page.getByRole('dialog', { name: '保存详情确认', exact: true });
  await expect(saveConfirmation).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(saveConfirmation).toHaveCount(0);
  await expect(saveEntry).toHaveAttribute('aria-expanded', 'true');
  await page.getByRole('button', { name: '重试原操作', exact: true }).click();
  await expect(page.getByRole('button', { name: '重试原操作', exact: true })).toHaveCount(0);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '触发警告', exact: true }).click();
  await expect(page.locator('.studio-message .ant-message-warning')).toBeVisible();
  expect(await editor.boundingBox()).toEqual(original);
  await expect(editor).toHaveValue('保留当前剧本输入');
  await page.getByRole('button', { name: '打开操作弹窗', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '反馈层级验收' });
  await dialog.evaluate(async element => { await Promise.all(element.getAnimations().map(animation => animation.finished)); });
  const dialogEditor = dialog.getByRole('textbox', { name: '弹窗编辑器', exact: true });
  const dialogSize = await dialogEditor.boundingBox();
  await dialog.getByRole('button', { name: '弹窗上传', exact: true }).click();
  await expect(dialog.locator('.studio-message')).toBeVisible();
  expect(await dialogEditor.boundingBox()).toEqual(dialogSize);
  await dialog.getByRole('button', { name: '关闭提示', exact: true }).click();
  const dialogEntry = dialog.getByRole('button', { name: /提示详情/ });
  await dialogEntry.click();
  await dialog.getByRole('button', { name: '重试弹窗上传', exact: true }).focus();
  await page.keyboard.press('Escape');
  await expect(dialogEntry).toBeFocused();
  await expect(dialogEntry).toHaveAttribute('aria-expanded', 'false');
  await expect(dialog).toBeVisible();
  await dialogEntry.press('Enter');
  await dialog.getByRole('button', { name: '弹窗详情内确认', exact: true }).click();
  const dialogConfirmation = page.getByRole('dialog', { name: '弹窗详情确认', exact: true });
  await expect(dialogConfirmation).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(dialogConfirmation).toHaveCount(0);
  await expect(dialogEntry).toHaveAttribute('aria-expanded', 'true');
  await expect(dialog).toBeVisible();
  await dialog.getByRole('button', { name: '重试弹窗上传', exact: true }).click();
  await expect(dialogEditor).toHaveValue('保留弹窗输入');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `.runtime/feedback-${width}.png` });
  expect(errors).toEqual([]);
});
